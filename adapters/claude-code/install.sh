#!/usr/bin/env bash
set -euo pipefail

BASELINE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ADAPTER_DIR="$BASELINE_DIR/adapters/claude-code"
GLOBAL_CLAUDE_DIR="$HOME/.claude"
GLOBAL_CLAUDE_MD="$GLOBAL_CLAUDE_DIR/CLAUDE.md"

echo "Installing Claude Code adapter..."

# Check for claude CLI
if ! command -v claude &>/dev/null; then
  echo "  Warning: 'claude' not found in PATH. Skipping Claude Code adapter."
  echo "  Install Claude Code first: https://claude.ai/code"
  exit 0
fi

# Check required plugins for the development lifecycle pipeline
echo "  Checking required plugins..."
PLUGINS_JSON="$GLOBAL_CLAUDE_DIR/plugins/installed_plugins.json"
MISSING_PLUGINS=()

check_plugin() {
  local plugin_key="$1"
  local plugin_name="$2"
  if [[ -f "$PLUGINS_JSON" ]]; then
    if ! node -e "const p=require('$PLUGINS_JSON'); process.exit(p.plugins && p.plugins['$plugin_key'] ? 0 : 1)" 2>/dev/null; then
      MISSING_PLUGINS+=("$plugin_name")
    fi
  else
    MISSING_PLUGINS+=("$plugin_name (plugins registry not found)")
  fi
}

check_plugin "superpowers@claude-plugins-official" "superpowers"
check_plugin "context-mode@context-mode" "context-mode"

GSD_SKILL="$GLOBAL_CLAUDE_DIR/skills/gsd-plan-phase"
if [[ ! -f "$GSD_SKILL" ]]; then
  MISSING_PLUGINS+=("get-shit-done (GSD)")
fi

if [[ ${#MISSING_PLUGINS[@]} -gt 0 ]]; then
  echo ""
  echo "  ⚠️  Missing required plugins for the development lifecycle pipeline:"
  for p in "${MISSING_PLUGINS[@]}"; do
    echo "     - $p"
  done
  echo ""
  echo "  Install missing plugins in Claude Code:"
  echo "     superpowers:   /install superpowers"
  echo "     context-mode:  /install context-mode"
  echo "     GSD:           https://github.com/paukertomas/get-shit-done"
  echo ""
else
  echo "  All required plugins present."
fi

# --- Global install (~/.claude/CLAUDE.md) ---
# The global file uses absolute paths so it works in any project directory.
# Generated from the adapter template with BASELINE_DIR substituted in.

mkdir -p "$GLOBAL_CLAUDE_DIR"

if [[ -f "$GLOBAL_CLAUDE_MD" && ! -L "$GLOBAL_CLAUDE_MD" ]]; then
  BACKUP="$GLOBAL_CLAUDE_MD.bak.$(date +%Y%m%d%H%M%S)"
  cp "$GLOBAL_CLAUDE_MD" "$BACKUP"
  echo "  Backed up existing ~/.claude/CLAUDE.md to $(basename "$BACKUP")"
fi

{
  printf "# Agent Configuration (Global)\n\n"
  printf "Your full configuration lives in the agentic baseline repository at:\n"
  printf "\`%s\`\n\n" "$BASELINE_DIR"
  printf "This file is auto-generated by the Claude Code adapter install script.\n"
  printf "To regenerate after moving the baseline repo, re-run:\n"
  printf "  %s/adapters/claude-code/install.sh\n\n" "$BASELINE_DIR"
  tail -n +6 "$ADAPTER_DIR/CLAUDE.md" | sed "s|core/|${BASELINE_DIR}/core/|g"
} > "$GLOBAL_CLAUDE_MD"

echo "  Generated ~/.claude/CLAUDE.md with absolute paths to $BASELINE_DIR"

# --- Repo root CLAUDE.md (relative paths — only useful inside the baseline repo itself) ---
cp "$ADAPTER_DIR/CLAUDE.md" "$BASELINE_DIR/CLAUDE.md"
echo "  Regenerated CLAUDE.md at baseline repo root (relative paths)"

echo ""
echo "  Claude Code adapter installed."
echo ""
echo "  Global:      ~/.claude/CLAUDE.md (absolute paths — applies to all projects)"
echo "  Baseline:    $BASELINE_DIR/CLAUDE.md (relative paths — for use inside this repo)"
echo ""
echo "  Validate: open a new Claude Code session in any directory and ask:"
echo "  'What do you know about my personal context, available tools, and escalation rules?'"
