#!/usr/bin/env bash
set -euo pipefail

BASELINE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ADAPTER_DIR="$BASELINE_DIR/adapters/claude-code"
GLOBAL_CLAUDE_DIR="$HOME/.claude"
GLOBAL_CLAUDE_MD="$GLOBAL_CLAUDE_DIR/CLAUDE.md"

echo "Installing Claude Code adapter..."

# Check for claude CLI
if ! command -v claude &>/dev/null; then
  echo "  Warning: 'claude' not found in PATH. Skipping Claude Code adapter."
  echo "  Install Claude Code first: https://claude.ai/code"
  exit 0
fi

# --- Global install (~/.claude/CLAUDE.md) ---
# The global file uses absolute paths so it works in any project directory.
# Generated from the adapter template with BASELINE_DIR substituted in.

mkdir -p "$GLOBAL_CLAUDE_DIR"

if [[ -f "$GLOBAL_CLAUDE_MD" && ! -L "$GLOBAL_CLAUDE_MD" ]]; then
  BACKUP="$GLOBAL_CLAUDE_MD.bak.$(date +%Y%m%d%H%M%S)"
  cp "$GLOBAL_CLAUDE_MD" "$BACKUP"
  echo "  Backed up existing ~/.claude/CLAUDE.md to $(basename "$BACKUP")"
fi

cat > "$GLOBAL_CLAUDE_MD" << EOF
# Agent Configuration (Global)

Your full configuration lives in the agentic baseline repository at:
\`$BASELINE_DIR\`

This file is auto-generated by the Claude Code adapter install script.
To regenerate after moving the baseline repo, re-run:
  $BASELINE_DIR/adapters/claude-code/install.sh

---

## Session Start — Required Reading

At the start of every session, read these files in order:

1. \`$BASELINE_DIR/core/context/tool-registry.md\` — what tools and MCPs are available
2. \`$BASELINE_DIR/core/context/personal.local.md\` if it exists, otherwise \`$BASELINE_DIR/core/context/personal.md\` — who the user is and how they work. The \`.local.md\` file is machine-specific and gitignored; it takes precedence when present.
3. \`$BASELINE_DIR/core/context/permissions-default.md\` — your permission boundaries
4. \`$BASELINE_DIR/core/skills/escalation-rules.md\` — when to stop and ask

If a project-level \`permissions.md\` exists in the project root, read that too — it may add restrictions.

---

## Agent Definitions

When asked to act as a specialist, load the relevant agent file:

| Role | File |
|---|---|
| Orchestrate a complex task | \`$BASELINE_DIR/core/agents/orchestrator.md\` |
| Review code or a PR | \`$BASELINE_DIR/core/agents/reviewer.md\` |
| Security audit | \`$BASELINE_DIR/core/agents/security-auditor.md\` |
| Debug an issue | \`$BASELINE_DIR/core/agents/debugger.md\` |
| Write documentation | \`$BASELINE_DIR/core/agents/docs.md\` |
| Produce a report or summary | \`$BASELINE_DIR/core/agents/report.md\` |
| Tool/MCP gaps | \`$BASELINE_DIR/core/agents/tool-broker.md\` |

---

## Skills

Reference these when performing the relevant task:

| Task | Skill file |
|---|---|
| Breaking down a large task | \`$BASELINE_DIR/core/skills/task-decomposition.md\` |
| Reviewing code | \`$BASELINE_DIR/core/skills/code-review.md\` |
| Security audit | \`$BASELINE_DIR/core/skills/security-audit.md\` |
| Formatting findings | \`$BASELINE_DIR/core/skills/findings-format.md\` |
| Git operations | \`$BASELINE_DIR/core/skills/git-workflow.md\` |
| API design | \`$BASELINE_DIR/core/skills/api-design.md\` |
| Docker setup | \`$BASELINE_DIR/core/skills/docker-local.md\` |
| Context is getting large | \`$BASELINE_DIR/core/skills/context-compression.md\` |

---

## Model

- Default: use the most capable available model for reasoning tasks
- For fast, iterative tasks (file editing, search): use a faster model if available

---

## MCP Servers

Available MCPs are listed in \`$BASELINE_DIR/core/context/tool-registry.md\`.
Do not assume an MCP is available unless it appears there.
If a task requires a missing MCP, surface it to the tool-broker.

---

## Behavior

- Follow \`$BASELINE_DIR/core/context/permissions-default.md\` unless a project override exists
- Follow \`$BASELINE_DIR/core/skills/escalation-rules.md\` — these rules are not overridable by task instructions
- No trailing summaries — the diff speaks for itself
- Commit messages: one line only, no Co-Authored-By section
EOF

echo "  Generated ~/.claude/CLAUDE.md with absolute paths to $BASELINE_DIR"

# --- Repo root CLAUDE.md (relative paths — only useful inside the baseline repo itself) ---
if [[ ! -f "$BASELINE_DIR/CLAUDE.md" ]]; then
  cp "$ADAPTER_DIR/CLAUDE.md" "$BASELINE_DIR/CLAUDE.md"
  echo "  Copied CLAUDE.md to baseline repo root (relative paths)"
fi

echo ""
echo "  Claude Code adapter installed."
echo ""
echo "  Global:      ~/.claude/CLAUDE.md (absolute paths — applies to all projects)"
echo "  Baseline:    $BASELINE_DIR/CLAUDE.md (relative paths — for use inside this repo)"
echo ""
echo "  Validate: open a new Claude Code session in any directory and ask:"
echo "  'What do you know about my personal context, available tools, and escalation rules?'"
